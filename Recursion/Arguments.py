def argument(clg,standard,name="harshita"):
    print("name= ",name)
    print("clg= ",clg)
    print("standard= ",standard)
#positional
argument("JU",12)
print() # Write only value
#default
argument("JU",12)
print()
# keyword
argument(clg="JU",standard=12,name="riya")# Write both key and value
print()